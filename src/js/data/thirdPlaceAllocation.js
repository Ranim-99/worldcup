/* Rank the twelve third-placed teams and return the best eight.
 * `thirds` is an array of objects, one per group:
 *   { group: 'A', pts, gd, gf }   (add conduct/fifaRank if you track them)
 * Returns the eight qualifying entries sorted by FIFA criteria. */
export function rankThirdPlacedTeams(thirds) {
  return [...thirds]
    .sort((a, b) =>
      (b.pts - a.pts) ||
      (b.gd - a.gd) ||
      (b.gf - a.gf) ||
      ((a.conduct || 0) - (b.conduct || 0)) ||   // fewer disciplinary pts is better
      ((a.fifaRank || 0) - (b.fifaRank || 0)))
    .slice(0, 8);
}

/* Given the eight qualifying group letters, return the R32 fills:
 *   [{ matchNum, slot: 'team2', thirdGroup }, ...]
 * Returns null if the combination isn't exactly eight of the twelve groups. */
export function allocateThirds(qualifyingGroups) {
  if (!Array.isArray(qualifyingGroups) || qualifyingGroups.length !== 8) return null;
  const key = [...qualifyingGroups].map((g) => g.toUpperCase()).sort().join('');
  const row = ANNEX_C[key];
  if (!row) return null;
  return row.split('').map((thirdGroup, col) => ({
    matchNum: THIRD_SLOT_MATCH[col],
    slot: 'team2',
    thirdGroup,
  }));
}

/* Convenience: rank the twelve thirds, then map each to its R32 slot.
 * `thirdsByGroup` maps group letter -> the third-placed team object
 *   { name, code, pts, gd, gf }
 * Returns [{ matchNum, slot, group, team }] for the eight qualifiers. */
export function assignThirds(thirdsByGroup) {
  const thirds = Object.entries(thirdsByGroup).map(([group, t]) => ({ group, ...t }));
  const best = rankThirdPlacedTeams(thirds);
  const fills = allocateThirds(best.map((t) => t.group));
  if (!fills) return null;
  return fills.map((f) => {
    const team = thirdsByGroup[f.thirdGroup];
    return { ...f, group: f.thirdGroup, team: { name: team.name, code: team.code } };
  });
}